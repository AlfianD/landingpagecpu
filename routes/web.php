Route::get('/blog/{slug}', function (string $slug) use ($blogPosts) {
    abort_unless(isset($blogPosts[$slug]), 404);

    $post = $blogPosts[$slug];
    $related = collect($blogPosts)->except($slug)->take(3);

    return view('blog-detail', [
        'title' => $post['title'] . ' — CiptaProgresa',
        'post' => $post,
        'slug' => $slug,
        'related' => $related,
    ]);
})->where('slug', '[a-z0-9-]+');


